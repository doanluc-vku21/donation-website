export function getCurrencyForCountry(
  country:
    | string
    | undefined
    | null,
): Currency {
  if (!country) {
    return defaultCurrency;
  }

  const normalized =
    country
      .trim()
      .toUpperCase();

  return (
    countryCurrencyMap[
      normalized
    ] ??
    defaultCurrency
  );
}
