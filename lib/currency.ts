export function getCurrencyMinorUnitExponent(
  currency: Currency,
): 0 | 2 | 3 {
  return (
    currencyMinorUnitExponents[
      currency
    ] ?? 2
  );
}

/**
 * Number of minor units that make one major unit.
 * USD -> 100, JPY -> 1, KWD -> 1000.
 */
export function getCurrencyMinorUnitFactor(
  currency: Currency,
): number {
  return 10 ** getCurrencyMinorUnitExponent(currency);
}

/**
 * Factor for a raw Stripe / ISO code where the value is not yet
 * narrowed to Currency. Unknown codes fall back to 2 decimals.
 */
export function getMinorUnitFactorForCode(
  code:
    | string
    | undefined
    | null,
): number {
  const normalized =
    (
      code ?? ""
    )
      .trim()
      .toUpperCase();

  const exponent =
    (
      currencyMinorUnitExponents as
        Record<string, number | undefined>
    )[normalized];

  return 10 ** (
    exponent ?? 2
  );
}

export function isCurrency(
  value:
    | string
    | undefined
    | null,
): value is Currency {
  return currencies.includes(
    value as Currency,
  );
}

